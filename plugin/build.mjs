// Builds the Temporal task plugin without any npm dependency:
//   dist/temporal-task.js                      browser module (web designer)
//   dist/temporal-task.template.json           element template (also for the desktop Modeler)
//   dist/fluxnova-temporal-task/               Fluxnova Modeler desktop plugin folder
import { mkdirSync, readFileSync, writeFileSync, rmSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const src = join(here, 'src', 'temporal-task.js');
const dist = join(here, 'dist');
const pluginDir = join(dist, 'fluxnova-temporal-task');

const { TEMPLATE } = require(src);
const source = readFileSync(src, 'utf8');
const templateJson = JSON.stringify([ TEMPLATE ], null, 2) + '\n';

rmSync(dist, { recursive: true, force: true });
mkdirSync(join(pluginDir, 'element-templates'), { recursive: true });

copyFileSync(src, join(dist, 'temporal-task.js'));
writeFileSync(join(dist, 'temporal-task.template.json'), templateJson);

// Desktop plugin: the Modeler loads `script` with a <script> tag and reads
// bpmn-js modules from window.plugins (same contract as
// camunda-modeler-plugin-helpers' registerBpmnJSPlugin).
writeFileSync(join(pluginDir, 'client.js'), `/* Fluxnova Modeler plugin: Temporal task (generated by plugin/build.mjs) */
(function () {
  var module = { exports: {} };
  var exports = module.exports;
${source}
  var api = module.exports;
  window.plugins = window.plugins || [];
  window.plugins.push({ type: 'bpmn.modeler.additionalModules', plugin: api.TemporalTaskModule });
  console.log('[Temporal task plugin] registered');
})();
`);

writeFileSync(join(pluginDir, 'index.js'), `'use strict';

module.exports = {
  name: 'Fluxnova Temporal Task',
  script: './client.js',
  style: './style.css'
};
`);

writeFileSync(join(pluginDir, 'style.css'), `.djs-palette .entry.fluxnova-temporal-palette-entry img,
.djs-popup .entry.fluxnova-temporal-replace-entry img {
  width: 22px;
  height: 22px;
}
`);

writeFileSync(join(pluginDir, 'element-templates', 'temporal-task.json'), templateJson);

writeFileSync(join(pluginDir, 'README.md'), `# Fluxnova Temporal Task plugin

Adds a **Temporal task** to the Fluxnova Modeler: a palette entry, a
"Temporal task" option in the change-type menu, a badge on the shape, and a
"Temporal workflow" section in the properties panel.

## Install

1. Close Fluxnova Modeler.
2. Copy this \`fluxnova-temporal-task\` folder into the Modeler's \`resources/plugins\` directory:
   - macOS: \`/Applications/Fluxnova Modeler.app/Contents/MacOS/resources/plugins\`
   - Windows: \`C:\\Program Files\\Fluxnova Modeler\\resources\\plugins\`
   - Linux: \`<install dir>/resources/plugins\`
3. Optional: also copy \`element-templates/temporal-task.json\` into
   \`resources/element-templates\` (the plugin registers the template itself).
4. Start the Modeler. The palette shows a new task icon with a purple dot.

A Temporal task is an external service task on topic \`temporal\`. It runs
when the Fluxnova -> Temporal bridge from the lab is connected to the engine.
`);

console.log('Built', dist);
